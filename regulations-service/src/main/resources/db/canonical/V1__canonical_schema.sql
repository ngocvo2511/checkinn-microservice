-- Canonical fresh-database bootstrap. Explicit opt-in only; never replay on legacy databases.

SET search_path TO public;

CREATE TABLE regulations (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    regulation_key varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    value varchar(255) NOT NULL,
    description varchar(2000),
    active boolean NOT NULL,
    version integer NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    PRIMARY KEY (id),
    UNIQUE (regulation_key),
    CHECK (version > 0)
);

CREATE TABLE regulation_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    regulation_key varchar(255) NOT NULL,
    regulation_name varchar(255) NOT NULL,
    version integer NOT NULL,
    snapshot_data text NOT NULL,
    applied_at timestamp(6) without time zone NOT NULL,
    source_user varchar(255),
    PRIMARY KEY (id),
    CHECK (version > 0)
);

CREATE TABLE regulation_event_outbox (
    id uuid NOT NULL,
    regulation_key varchar(255) NOT NULL,
    source_version integer NOT NULL,
    exchange_name varchar(255) NOT NULL,
    payload jsonb NOT NULL,
    state varchar(16) DEFAULT 'PENDING' NOT NULL,
    attempts integer DEFAULT 0 NOT NULL,
    last_error varchar(64),
    next_attempt_at timestamptz DEFAULT now() NOT NULL,
    created_at timestamptz DEFAULT now() NOT NULL,
    delivered_at timestamptz,
    CHECK (attempts >= 0),
    PRIMARY KEY (id),
    UNIQUE (regulation_key, source_version),
    CHECK (source_version > 0),
    CHECK (state::text = ANY (ARRAY['PENDING'::character varying, 'DELIVERED'::character varying]::text[]))
);

CREATE INDEX regulation_snapshots_applied ON public.regulation_snapshots (applied_at DESC);

CREATE INDEX regulation_event_due ON public.regulation_event_outbox USING btree (state, next_attempt_at);

CREATE INDEX regulation_event_pending ON public.regulation_event_outbox USING btree (regulation_key, source_version) WHERE ((state)::text = 'PENDING'::text);
